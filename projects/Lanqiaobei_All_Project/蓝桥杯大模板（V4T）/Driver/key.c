#include "key.h"

//检测按键被按下的函数 
unsigned char Key_Read()
{
	unsigned char temp=0;//没有按键按下，返回值为0
	
	//独立按键 (跳线帽接到独立按键区域，默认只有P44置为0)
	/*
	if(P30==0) temp=7;
	if(P31==0) temp=6;
	if(P32==0) temp=5;
	if(P33==0) temp=4;
	*/
	//矩阵按键
	//#1、如果需要测量频率，需要注释掉所有P34相关的东西
	//如果按键所有列未使能（选中），但P30等于0，说明P30被串口触发了，因为P30引脚只用于串口和按键
	P44=1;P42=1;P35=1;//P34=1;
	if(P30==0) return 0;
	P44=0;P42=1;P35=1;//P34=1;//选中第一列
	if(P30==0) temp=7;
	if(P31==0) temp=6;
	if(P32==0) temp=5;
	if(P33==0) temp=4;
	
	P44=1;P42=1;P35=1;//P34=1;
	if(P30==0) return 0;
	P44=1;P42=0;P35=1;//P34=1;//选中第二列
	if(P30==0) temp=11;
	if(P31==0) temp=10;
	if((P32==0)&&(P33==0)) return 89;//双按键同时被按下
	if(P32==0) temp=9;
	if(P33==0) temp=8;
	
	P44=1;P42=1;P35=1;//P34=1;
	if(P30==0) return 0;
	P44=1;P42=1;P35=0;//P34=1;//选中第三列
	if(P30==0) temp=15;
	if(P31==0) temp=14;
	if(P32==0) temp=13;
	if(P33==0) temp=12;
	
//	P44=1;P42=1;P35=1;P34=1;
//	if(P30==0) return 0;
//	P44=1;P42=1;P35=1;P34=0;//选中第四列
//	if(P30==0) temp=19;
//	if(P31==0) temp=18;
//	if(P32==0) temp=17;
//	if(P33==0) temp=16;

	P44=1;P42=1;P35=1;P34=1;
	P3=P3|0xef;
	//1110 1111 在不影响我们的频率的情况下（P34或上0，则P34原来是什么还是什么），
	//把P3口的其他位置为1，让P3变为双向口接收
	return temp;

}