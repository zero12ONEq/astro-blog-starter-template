/**********************************************************************
 * 文件名: uart.c
 * 功能描述: 串口通信模块，实现串口初始化和字符发送功能
 * 包含功能:
 *   - 串口1初始化(9600bps@12MHz)
 *   - 标准库putchar函数重定向实现
 **********************************************************************/

#include "uart.h"
#include "stdio.h"

/**
 * 功能: 串口1初始化
 * 描述:
 *   - 配置波特率为9600bps(基于12MHz时钟)
 *   - 配置为8位数据位，可变波特率模式
 *   - 使用定时器2作为波特率发生器
 *   - 开启串口接收中断
 */
void Uart1_Init(void) // 9600bps@12.000MHz
{
	SCON = 0x50;  // 配置为模式1(8位数据，可变波特率)
	AUXR |= 0x01; // 串口1选择定时器2为波特率发生器
	AUXR &= 0xFB; // 定时器时钟12T模式
	T2L = 0xE6;	  // 设置定时初始值(波特率相关)
	T2H = 0xFF;	  // 设置定时初始值(波特率相关)
	AUXR |= 0x10; // 定时器2开始计时
}

/**
 * 功能: 标准库putchar函数重定向
 * 描述:
 *   - 通过重定义putchar函数，使printf可以通过串口输出
 *   - 发送一个字符并等待发送完成
 * 参数:
 *   ch - 要发送的字符
 * 返回值:
 *   发送的字符
 */
extern char putchar(char ch)
{
	SBUF = ch; // 将字符写入串口缓冲区
	while (TI == 0)
		;	   // 等待发送完成(TI为发送中断标志位)
	TI = 0;	   // 清除发送中断标志位
	return ch; // 返回发送的字符
}