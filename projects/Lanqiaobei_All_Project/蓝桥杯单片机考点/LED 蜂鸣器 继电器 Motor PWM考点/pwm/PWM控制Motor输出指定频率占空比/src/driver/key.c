 #include "key.h"

 /**
  * 功能: 读取按键状态
  * 描述: 通过矩阵扫描方式读取按键状态
  *       使用的引脚:
  *       - 行: P44, P42, P35（原本还有P34但已注释）
  *       - 列: P30, P31, P32, P33
  * 返回: 按键编码值(0表示无键按下)
  *       - 矩阵键盘第一行: 4, 5, 6, 7
  *       - 矩阵键盘第二行: 8, 9, 10, 11
  *       - 矩阵键盘第三行: 12, 13, 14, 15
  *       - 矩阵键盘第四行: 16, 17, 18, 19 (已注释)
  */
 unsigned char Key_Read()
 {
	 unsigned char temp = 0;
	 
	 // 如果使用串口，那么我们需要关闭波特率发生器
	 // AUXR &= ~(0x10);		// 定时器2停止计时
	 
	 // 如果需要对NE555测量，那么必须注释P34所有内容，最后一列，以及所有涉及到P34的判断
	 
	 /* 独立按键读取方式(备注) */
	 //	if(P30==0)temp=7;
	 //	if(P31==0)temp=6;
	 //	if(P32==0)temp=5;
	 //	if(P33==0)temp=4;
			 
	 /* 矩阵键盘扫描(第一行) */
	 P44=0;P42=1;P35=1;//P34=1;  // 第一行置低，其余行置高
	 if(P30==0)temp=7;           // 检测第一列
	 if(P31==0)temp=6;           // 检测第二列
	 if(P32==0)temp=5;           // 检测第三列
	 if(P33==0)temp=4;           // 检测第四列
	 
	 /* 矩阵键盘扫描(第二行) */
	 P44=1;P42=0;P35=1;//P34=1;  // 第二行置低，其余行置高
	 if(P30==0)temp=11;          // 检测第一列
	 if(P31==0)temp=10;          // 检测第二列
	 if(P32==0)temp=9;           // 检测第三列
	 if(P33==0)temp=8;           // 检测第四列
	 
	 /* 矩阵键盘扫描(第三行) */
	 P44=1;P42=1;P35=0;//P34=1;  // 第三行置低，其余行置高
	 if(P30==0)temp=15;          // 检测第一列
	 if(P31==0)temp=14;          // 检测第二列
	 if(P32==0)temp=13;          // 检测第三列
	 if(P33==0)temp=12;          // 检测第四列
	 
	 /* 矩阵键盘扫描(第四行)(已注释) */
	 // P44=1;P42=1;P35=1;P34=0;  // 第四行置低，其余行置高
	 // if(P30==0)temp=19;         // 检测第一列
	 // if(P31==0)temp=18;         // 检测第二列
	 // if(P32==0)temp=17;         // 检测第三列
	 // if(P33==0)temp=16;         // 检测第四列
 
	 // 恢复P3口初始状态与打开波特率发生器(已注释)
	 // P3 = 0xff;
	 // AUXR |= 0x10;		// 定时器2开始计时
	 
	 return temp;  // 返回按键编码
 }